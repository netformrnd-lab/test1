// 텍스트에서 동(棟)들을 뽑아냄 — 줄임표기("102,3동"=102·103동)·범위("103~106동") 풀어줌
// base: 단지가 100동대면 100 지정 → 2자리 동(21동)을 121동으로 보정
window.parseDongs = function (text, base) {
  base = parseInt(base, 10) || 0;
  const hund = base ? String(Math.floor(base / 100)) : ''; // 예: base 100 → '1'
  let s = ' ' + String(text || '') + ' ';
  const out = [];
  const push = (n) => { n = parseInt(n, 10); if (!isNaN(n)) { if (base && n < 100) n = n + base; const d = n + '동'; if (out.indexOf(d) < 0) out.push(d); } };
  const rangeExpand = (m, a, b) => {
    let lo = parseInt(a, 10), hi = parseInt(b, 10); if (hi < lo) { const t = lo; lo = hi; hi = t; }
    if (hi - lo <= 40) { for (let i = lo; i <= hi; i++) push(i); }
    return '  ';
  };
  // 1) 물결표 범위: 103~106동 (항상 범위)
  s = s.replace(/(\d{1,3})\s*동?\s*[~～]\s*(\d{1,3})\s*동/g, rangeExpand);
  // 1-2) 붙임표: 자릿수 같으면 범위(101-105동), 다르면 접두(1-21동=121)로 그룹 처리에 넘김
  s = s.replace(/(\d{1,3})\s*동?\s*-\s*(\d{1,3})\s*동/g, (m, a, b) => (a.length === b.length ? rangeExpand(m, a, b) : m));
  // 2) 콤마/가운뎃점/붙임표 묶음: 102,3동 / 102,103동 / 1-21동(=121, base 단지)
  s = s.replace(/(\d{1,3}(?:\s*[,·\/，、\-]\s*\d{1,3})+)\s*동/g, (m, g) => {
    let nums = g.split(/\s*[,·\/，、\-]\s*/).filter(Boolean);
    // base 단지에서 맨 앞이 백단위 접두('1')면 접두로 처리: "1-21동"=121, "1,21,22동"=121,122
    if (base && nums.length >= 2 && nums[0] === hund) nums = nums.slice(1);
    let prev = null;
    nums.forEach(ns => {
      let n;
      if (prev != null && ns.length < String(prev).length) {
        const p = String(prev); n = parseInt(p.slice(0, p.length - ns.length) + ns, 10);
      } else { n = parseInt(ns, 10); }
      push(n); prev = n;
    });
    return '  ';
  });
  // 3) 남은 단일 N동
  s.replace(/(\d{1,3})\s*동/g, (m, a) => { push(a); return '  '; });
  return out.sort((a, b) => (parseInt(a) || 999) - (parseInt(b) || 999));
};
